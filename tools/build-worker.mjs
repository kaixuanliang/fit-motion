import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

/**
 * 把 src/render/tile-worker.ts 打成单文件 IIFE，并以字符串常量的形式
 * 生成 src/render/tile-worker.gen.ts（运行时用 Blob URL 创建 Worker）。
 *
 * 为什么不直接 new Worker(new URL(...))：产物只有一个 app.js 且跑在
 * file://（APK android_asset）下，外部 worker 文件在 file:// 会被拦。
 * 为什么不用 Vite 的 ?worker&inline：构建走的是 esbuild CLI（无插件）。
 *
 * build-web.mjs 每次构建都会先跑本脚本；dev 模式若改动了 tile-worker /
 * tile-painter，请手动重跑一次 node tools/build-worker.mjs。
 */

const root = process.cwd();
const exe = path.join(root, 'node_modules', '@esbuild', 'win32-x64', 'esbuild.exe');
const outfile = path.join(root, 'dist', 'tile-worker.bundle.js');

const result = spawnSync(exe, [
  'src/render/tile-worker.ts',
  '--bundle',
  '--minify',
  '--format=iife',
  '--target=es2019',
  `--outfile=${outfile}`,
  '--log-level=warning',
], { stdio: 'inherit', cwd: root });
if (result.status !== 0) process.exit(result.status ?? 1);

const js = fs.readFileSync(outfile, 'utf8');
const gen = `// AUTO-GENERATED by tools/build-worker.mjs — 请勿手改。
// 重新生成：node tools/build-worker.mjs（build-web.mjs 会自动执行）。
// 源码：src/render/tile-worker.ts（含 tile-painter 绘制逻辑）。
export const TILE_WORKER_SOURCE = ${JSON.stringify(js)};
`;
fs.writeFileSync(path.join(root, 'src', 'render', 'tile-worker.gen.ts'), gen);
fs.rmSync(outfile, { force: true });
console.log(`tile-worker bundle: ${(Buffer.byteLength(js) / 1024).toFixed(1)} KB → src/render/tile-worker.gen.ts`);
